public class Binding extends Glyph {

	private static Glowing BLACK = new Glowing( 0x000000 );

    // must be implemented according to the glyph class
    // but this curse does not need it, so just leave it
	@Override
	public int proc( Armor armor, Char attacker, Char defender, int damage) {
		return damage;
	}


    // this is effectively the whole gimmick of the curse, one single boolean
    @Override
    public boolean removableByUpgrade() {
        return false;
    }
	@Override
	public Glowing glowing() {
		return BLACK;
	}

	@Override
	public boolean curse() {
		return true;
	}
}
